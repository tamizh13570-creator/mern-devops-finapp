//git --version 2.34.1 -> to check the version of git installed on your system.
//git init -> to initialize a new git repository in your project folder.
// git status -> to check the status of your git repository, including untracked files and changes.
// git add <file> -> to stage a specific file for commit.
// git add . -> to stage all changes in the current directory for commit.
// git commit -m "commit message" -> to commit the staged changes with a descriptive message.
//git commit -m "Initial commit" -> to make the first commit in the repository. 
// git log -> to view the commit history of the repository.
// git branch -> to list all branches in the repository.
// git checkout <branch> -> to switch to a specific branch.
// git merge <branch> -> to merge changes from a specific branch into the current branch.
// git remote add origin <repository-url> -> to add a remote repository to your local repository.
// git push -u origin <branch> -> to push your local commits to the remote repository on a specific branch.
// git pull -> to fetch and merge changes from the remote repository into your local repository. 
//  git fetch origin -> to fetch changes from the remote repository without merging them into your local branch.